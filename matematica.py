def somar(a, b):
    return a + b

def subtrair(a, b):
    return a - b

def multi(a, b):
    return int(a) * int(b) 


def quadrado(numero):
    return float(numero) * float(numero)


def divisao_inteira(dividendo, divisor):
   
    if divisor == 0:
        return None  
    return dividendo // divisor

def dividir(a, b, c):
    return (int(a) + int(b) + int(c) )/3